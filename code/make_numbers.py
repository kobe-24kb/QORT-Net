"""Write every number quoted in the text as a LaTeX macro (tables/numbers.tex).

Macro names contain letters only. Dataset codes: XjtuTwo (XJTU-SY C2, development),
PhmOne (PHM2012 C1, development), XjtuOne (XJTU-SY C1, held-out), PhmTwo (PHM2012 C2,
held-out), PhmSixty (PHM2012 C1 decimated to 60 s).
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
SOURCE = ROOT / "source_data"
OUT = ROOT / "manuscript" / "tables" / "numbers.tex"

D = {"xjtu": "XjtuTwo", "phm": "PhmOne", "xjtu_c1": "XjtuOne", "phm_c2": "PhmTwo", "phm60": "PhmSixty"}
M = {
    "qort_net": "Qort", "qort_prior_only": "Prior", "median_lifetime_clock": "Clock",
    "constant_05": "Const", "ridge_linear_vibration": "Ridge", "gru_time_prior": "GruTP",
    "film_time_prior": "FilmTP", "patchtst_time_prior": "PatchTP", "gru": "Gru", "film": "Film",
    "filternet": "Filter", "patchtst": "Patch", "pca_drsn_tcn": "Drsn", "mixlinear": "Mix",
    "vpnet": "Vp", "qort_single_prior": "Single", "qort_static_gate": "Static",
    "qort_no_relative_view": "NoRel", "qort_vibration_only": "VibOnly", "qort_no_aux": "NoAux", "qort_no_spectral": "NoSpec", "qort_no_trend": "NoTrend",
    "qort_raw": "Raw", "qort_no_optimism": "NoOpt",
    "qort_router_r0": "RZero", "qort_router_r05": "RHalf", "qort_router_r1": "ROne",
    "qort_gate_base_const": "GConst", "gru_time_prior_budget": "GruBudget",
    "film_time_prior_budget": "FilmBudget", "qort_w20_10": "WinShort", "qort_w80_40": "WinLong",
}
S = {"held-out": "Held", "development": "Dev", "all": "All", "xjtu": "XjtuTwo", "phm": "PhmOne",
     "xjtu_c1": "XjtuOne", "phm_c2": "PhmTwo"}

lines: list[str] = ["% Generated by code/make_numbers.py -- do not edit by hand."]


defined: set[str] = set()


def define(name: str, value: str) -> None:
    if name in defined:
        return
    defined.add(name)
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def num(value, digits=3, signed=False) -> str:
    if value is None or (isinstance(value, float) and np.isnan(value)):
        return "--"
    return f"{value:+.{digits}f}".replace("+", "+") if signed else f"{value:.{digits}f}"


def pval(value) -> str:
    if value is None or np.isnan(value):
        return "--"
    return f"{value:.3f}" if value >= 0.001 else f"{value:.4f}"


def main() -> None:
    summary = pd.read_csv(SOURCE / "dataset_summary.csv")
    for _, r in summary.iterrows():
        if r.dataset not in D or r.model not in M:
            continue
        key = D[r.dataset] + M[r.model]
        define("mae" + key, num(r.mae))
        define("rmse" + key, num(r.rmse))
        define("maesd" + key, num(r.mae_sd))
        define("ciL" + key, num(r.mae_ci_low))
        define("ciH" + key, num(r.mae_ci_high))
        define("late" + key, num(r.late_mae))
        define("viol" + key, num(r.violation))
        define("min" + key, num(r.minutes, 1))
        define("seedsd" + key, num(r.seed_sd))

    pairs = pd.read_csv(SOURCE / "paired_inference.csv")
    for _, r in pairs.iterrows():
        if r.scope not in S or r.comparator not in M:
            continue
        key = S[r.scope] + M[r.comparator]
        define("diff" + key, num(r.mean_diff, signed=True))
        define("mdiff" + key, num(r.median_diff, signed=True))
        define("dciL" + key, num(r.ci_low, signed=True))
        define("dciH" + key, num(r.ci_high, signed=True))
        define("pperm" + key, pval(r.p_signflip))
        define("pwil" + key, pval(r.p_wilcoxon))
        define("pwilone" + key, pval(r.p_wilcoxon_one_sided))
        define("wins" + key, f"{int(r.wins)}")
        define("npair" + key, f"{int(r.n)}")
        define("rbis" + key, num(r.rank_biserial, 2, signed=True))
        if "p_signflip_holm" in r and not pd.isna(r.p_signflip_holm):
            define("pholm" + key, pval(r.p_signflip_holm))

    mixed = pd.read_csv(SOURCE / "mixed_effects.csv")
    for _, r in mixed.iterrows():
        key = M[r.comparison.split(" - ")[1]]
        define("mixDev" + key, num(r.development_effect, signed=True))
        define("mixDevL" + key, num(r.development_ci_low, signed=True))
        define("mixDevH" + key, num(r.development_ci_high, signed=True))
        define("mixHeld" + key, num(r.held_out_effect, signed=True))
        define("mixHeldL" + key, num(r.held_out_ci_low, signed=True))
        define("mixHeldH" + key, num(r.held_out_ci_high, signed=True))
        define("mixShiftP" + key, pval(r.held_out_shift_p))

    ab = pd.read_csv(SOURCE / "ablation_three_seed.csv")
    for _, r in ab.iterrows():
        if r.model == "qort_net" or r.model not in M:
            continue
        key = D[r.dataset] + M[r.model]
        define("abl" + key, num(r.diff_vs_full, signed=True))

    folds = pd.read_csv(SOURCE / "fold_router_values.csv")
    for d, g in folds.groupby("dataset"):
        define("cvMin" + D[d], num(g.lifetime_cv.min()))
        define("cvMax" + D[d], num(g.lifetime_cv.max()))
        define("rMin" + D[d], num(g.regime_weight.min()))
        define("rMax" + D[d], num(g.regime_weight.max()))

    corr = json.loads((SOURCE / "atypical_correlations.json").read_text())
    for key, name in (("gain_vs_clock", "Clock"), ("gain_vs_prior_only", "Prior"),
                      ("single_minus_full", "Single"), ("static_minus_full", "Static")):
        if key in corr:
            define("rhoAtyp" + name, num(corr[key]["spearman_rho"], 2, signed=True))
            define("pAtyp" + name, pval(corr[key]["p"]))
    for model, values in corr.get("error_vs_abs_deviation", {}).items():
        define("rhoErr" + M[model], num(values["spearman_rho"], 2, signed=True))
        define("pErr" + M[model], pval(values["p"]))
    g = corr["groups"]
    define("nAtypical", str(g["atypical_n"]))
    define("nTypical", str(g["typical_n"]))
    define("gainClockAtypical", num(g["atypical_gain_vs_clock"], signed=True))
    define("gainClockTypical", num(g["typical_gain_vs_clock"], signed=True))
    define("gainPriorAtypical", num(g["atypical_gain_vs_prior_only"], signed=True))
    define("gainPriorTypical", num(g["typical_gain_vs_prior_only"], signed=True))

    stages = pd.read_csv(SOURCE / "life_stage_errors.csv")
    for model, g2 in stages.groupby("model"):
        for stage in ("early", "middle", "late"):
            define("stage" + stage.capitalize() + M[model], num(g2[stage].mean()))

    film = pd.read_csv(SOURCE / "film_versus_qort_diagnosis.csv")
    for d, g2 in film.groupby("dataset"):
        for model, name in (("qort_net", "Qort"), ("film_time_prior", "FilmTP"), ("gru_time_prior", "GruTP")):
            define("distClock" + D[d] + name, num(g2[f"{model}_dist_clock"].mean()))
            define("tv" + D[d] + name, num(g2[f"{model}_tv"].mean(), 4))

    for path, prefix in (("training_subset_summary.csv", "sub"),):
        p = SOURCE / path
        if p.exists():
            sub = pd.read_csv(p)
            for _, r in sub.iterrows():
                key = D[r.dataset] + M[r.model]
                define(prefix + "Full" + key, num(r.mae_full))
                define(prefix + "Mean" + key, num(r.mae_subset_mean))
                define(prefix + "AbsDelta" + key, num(r.mean_abs_delta))
                define(prefix + "MaxDelta" + key, num(r.max_delta, signed=True))
                define(prefix + "SD" + key, num(r.within_fold_sd))
                define(prefix + "Rho" + key, num(r.spearman_absL50_absdelta, 2, signed=True))
                define(prefix + "LfiftyChange" + D[r.dataset], f"{100 * r.mean_abs_rel_L50_change:.0f}")
                define(prefix + "LfiftyMax" + D[r.dataset], f"{100 * r.max_abs_rel_L50_change:.0f}")

    p = SOURCE / "prior_shift_summary.csv"
    if p.exists():
        shift = pd.read_csv(p)
        factor_cols = [c for c in shift.columns if c not in ("dataset", "model")]
        names = {"0.7": "Seventy", "0.85": "EightyFive", "1.0": "Hundred", "1.15": "HundredFifteen",
                 "1.3": "HundredThirty"}
        for _, r in shift.iterrows():
            for c in factor_cols:
                if c in names:
                    define("shift" + D[r.dataset] + M[r.model] + names[c], num(r[c]))
            values = [r[c] for c in factor_cols if c in names]
            define("shiftMin" + D[r.dataset] + M[r.model], num(min(values)))
            define("shiftMax" + D[r.dataset] + M[r.model], num(max(values)))
            for c in factor_cols:
                if c in names and c != "1.0":
                    define("shiftDelta" + D[r.dataset] + M[r.model] + names[c], num(r[c] - r["1.0"], signed=True))
        # largest absolute MAE change over all factors, per condition, then its range over conditions
        for model, rows in shift.groupby("model"):
            worst = [max(abs(r[c] - r["1.0"]) for c in factor_cols if c in names) for _, r in rows.iterrows()]
            define("shiftWorstMin" + M[model], num(min(worst)))
            define("shiftWorstMax" + M[model], num(max(worst)))
        verification = json.loads((SOURCE / "checkpoint_reload_verification.json").read_text())
        mantissa, exponent = f"{verification['max_abs_mae_difference']:.1e}".split("e")
        define("reloadMaxDiff", f"${mantissa}\\times10^{{{int(exponent)}}}$")
        define("reloadRuns", str(verification["runs"]))

    p = SOURCE / "transfer_summary.csv"
    if p.exists():
        tr = pd.read_csv(p)
        for _, r in tr.iterrows():
            for model in ("qort_net", "qort_prior_only", "median_lifetime_clock", "gru_time_prior",
                          "film_time_prior"):
                if model in r:
                    define("tr" + D[r.source] + "To" + D[r.target] + M[model], num(r[model]))

    budget = pd.read_csv(SOURCE / "budget_and_grid.csv")
    keymap = {"QORT-Net": "Qort", "GRU + time/prior": "GruTP", "FiLM-inspired + time/prior": "FilmTP"}
    for _, r in budget.iterrows():
        for d in ("xjtu", "phm", "xjtu_c1", "phm_c2"):
            for k in ("default", "budget", "grid"):
                column = f"{d}_{k}"
                if column in r and not pd.isna(r[column]):
                    define(k + D[d] + keymap[r.model], num(r[column]))

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(lines) - 1} macros -> {OUT}")


if __name__ == "__main__":
    main()
